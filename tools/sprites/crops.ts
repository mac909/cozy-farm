const EMPTY = "................";

/** Pads bottom-anchored rows at the top so the frame is 16 rows tall. */
function tile(...rows: string[]): string[] {
  if (rows.length > 16) throw new Error(`Frame has ${rows.length} rows`);
  return [...Array<string>(16 - rows.length).fill(EMPTY), ...rows];
}

/** Stage 0 for most crops: three seeds in the soil. "z" and "Z" are the seed's colours. */
const SEEDS = tile(
  "......zz........",
  "......zZ...zz...",
  "...zz......zZ...",
  "...zZ...........",
  EMPTY,
  EMPTY,
);

export interface CropArt {
  /** Seed colour and its shade, used by the shared seed frame. */
  seed?: readonly [string, string];
  /** Growth stages from just planted to ripe. A "SEEDS" entry uses the shared seed frame. */
  stages: readonly (readonly string[])[];
  /** The harvested crop, as an inventory icon. */
  item: readonly string[];
  /** 8×8 picture printed on the seed packet. */
  packet: readonly string[];
}

