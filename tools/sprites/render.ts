/**
 * Renders our own sprites into client/public/assets/custom/ and writes
 * custom/manifest.json, which names every frame.
 *
 * Run with `npm run sprites` after editing any file in tools/sprites/.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { BEACH_ITEMS, BEACH_LEGEND } from "./beach";
import { BUG_IDS } from "../../shared/content/bugs";
import { FISH_IDS } from "../../shared/content/fish";
import { BUG_SHEET, bugFrames } from "./bugs";
import { FISH_ART } from "./fish";
import { FISHING_FRAMES, fishingFrames } from "./fishing";
import { crateClosed, crateOpen } from "./crate";
import { CROP_ART, CROP_LEGEND, PACKET, PACKET_PICTURE, SEEDS } from "./crops";
import { PACK_EMOTES, emoteFrames } from "./emotes";
import { Img, fromGrid, outline, packRows } from "./lib/image";
import { MARKERS } from "./markers";
import { seedStand } from "./seedStand";
import { FRAME, SEASIDE, SEASIDE_FRAMES } from "./seaside";
import { SAND_GRASS, SAND_WATER, recolourBlock } from "./sand";
import { soilTile } from "./soil";
import { UI_ICONS } from "./ui";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const PACK = path.join(ROOT, "client/public/assets/ninja-adventure");
const OUT = path.join(ROOT, "client/public/assets/custom");
const T = 16;

const manifest: Record<string, unknown> = {
  about: "Made for Cozy Farm in Ninja Adventure's style. Generated by `npm run sprites` from tools/sprites/; don't edit the PNGs by hand.",
};

function save(name: string, img: Img, info: Record<string, unknown>): void {
  img.write(path.join(OUT, `${name}.png`));
  manifest[name] = { file: `${name}.png`, width: img.w, height: img.h, ...info };
  console.log(`  ${name}.png  ${img.w}×${img.h}`);
}

function renderCrops(): void {
  const ITEM_COL = 5;
  const PACKET_COL = 6;
  const cols = PACKET_COL + 1;
  const rows: (Img | null)[][] = [];
  const crops: Record<string, unknown> = {};
  Object.entries(CROP_ART).forEach(([id, art], row) => {
    const legend = { ...CROP_LEGEND, ...("seed" in art ? { z: art.seed[0], Z: art.seed[1] } : {}) };
    if (art.stages.includes(SEEDS) && !("seed" in art)) throw new Error(`${id} uses SEEDS but has no seed colours`);
    const frames: (Img | null)[] = Array(cols).fill(null);
    art.stages.forEach((grid, i) => (frames[i] = outline(fromGrid(grid, legend))));
    frames[ITEM_COL] = outline(fromGrid(art.item, legend));
    const packet = fromGrid(PACKET, legend).blit(fromGrid(art.packet, legend), PACKET_PICTURE.x, PACKET_PICTURE.y);
    frames[PACKET_COL] = outline(packet);
    rows.push(frames);
    crops[id] = {
      stages: art.stages.map((_, i) => row * cols + i),
      item: row * cols + ITEM_COL,
      packet: row * cols + PACKET_COL,
    };
  });
  save("crops", packRows(rows, T, T), {
    frameWidth: T,
    frameHeight: T,
    layout: "One row per crop. Columns 0..n-1: growth stages, seed to ripe. Column 5: harvested item. Column 6: seed packet.",
    crops,
  });
}

function renderSoil(): void {
  const dry = Array.from({ length: 16 }, (_, mask) => soilTile(mask, false));
  const wet = Array.from({ length: 16 }, (_, mask) => soilTile(mask, true));
  save("soil", packRows([dry, wet], T, T), {
    frameWidth: T,
    frameHeight: T,
    layout:
      "Row 0 dry, row 1 watered. Frame = mask (+16 if watered), where mask adds 1/2/4/8 for each tilled neighbour to the north/east/south/west.",
  });
}

function renderBeachItems(): void {
  const names = Object.keys(BEACH_ITEMS);
  const frames = names.map((n) => outline(fromGrid(BEACH_ITEMS[n], BEACH_LEGEND)));
  save("beach-items", packRows([frames], T, T), {
    frameWidth: T,
    frameHeight: T,
    frames: Object.fromEntries(names.map((n, i) => [n, i])),
  });
}

function renderCrate(): void {
  save("shipping-crate", packRows([[outline(crateClosed()), outline(crateOpen())]], 32, 32), {
    frameWidth: 32,
    frameHeight: 32,
    frames: { closed: 0, open: 1 },
    note: "Two tiles wide. The box sits on the bottom of the frame.",
  });
}

function renderSeedStand(): void {
  save("seed-stand", outline(seedStand()), {
    frameWidth: 32,
    frameHeight: 32,
    note: "Two tiles wide and two tall: a market stall with seed sacks. The counter sits on the bottom of the frame.",
  });
}

function renderSand(): void {
  const blocks: Img[] = [];
  for (const [name, r] of [
    ["sand-grass", SAND_GRASS],
    ["sand-water", SAND_WATER],
  ] as const) {
    const img = recolourBlock(Img.read(path.join(PACK, r.source)), r);
    blocks.push(img);
    save(name, img, {
      frameWidth: T,
      frameHeight: T,
      recolouredFrom: `ninja-adventure/${r.source} (block at ${r.x},${r.y}, ${r.w}×${r.h}); same tile layout`,
    });
  }
  // One sheet for the map, so a single Tiled terrain set covers grass, sand and sea.
  const [grass, water] = blocks;
  const terrain = new Img(Math.max(grass.w, water.w), grass.h + water.h).blit(grass).blit(water, 0, grass.h);
  save("beach-terrain", terrain, {
    frameWidth: T,
    frameHeight: T,
    layout: `sand-grass.png on top (rows 0–${grass.h / T - 1}), sand-water.png below. The map's Ground layer uses it.`,
  });
}

function renderMarkers(): void {
  const names = Object.keys(MARKERS) as (keyof typeof MARKERS)[];
  save("map-markers", packRows([names.map((n) => MARKERS[n]())], T, T), {
    frameWidth: T,
    frameHeight: T,
    frames: Object.fromEntries(names.map((n, i) => [n, i])),
    note: "Painted on the map's hidden Collision and Farmland layers in Tiled. The game never draws them.",
  });
}

function renderEmotes(): void {
  const frames = emoteFrames((file) => Img.read(path.join(PACK, file)));
  const [fw, fh] = [frames[0].w, frames[0].h];
  save("emotes", packRows([frames], fw, fh), {
    frameWidth: fw,
    frameHeight: fh,
    frames: { wave: 0, heart: 1 },
    note: `In EMOTES order (shared/content/emotes.ts). Heart is the pack's ${PACK_EMOTES.heart}; wave is our hand in the pack's bubble.`,
  });
}

function renderUiIcons(): void {
  const names = Object.keys(UI_ICONS) as (keyof typeof UI_ICONS)[];
  save("ui-icons", packRows([names.map((n) => UI_ICONS[n]())], T, T), {
    frameWidth: T,
    frameHeight: T,
    frames: Object.fromEntries(names.map((n, i) => [n, i])),
  });
}

function renderSeaside(): void {
  const names = Object.keys(SEASIDE) as (keyof typeof SEASIDE)[];
  save("seaside-furniture", packRows([names.map((n) => outline(SEASIDE[n]()))], FRAME, FRAME), {
    frameWidth: FRAME,
    frameHeight: FRAME,
    frames: Object.fromEntries(names.map((n, i) => [n, { frame: i, ...SEASIDE_FRAMES[n] }])),
    note: "Each picture sits inside its 32×32 frame at the given rectangle; client/src/art/furnitureArt.ts cuts them out.",
  });
}

function renderFish(): void {
  const frames = FISH_IDS.map((id) => outline(fromGrid(FISH_ART[id].grid, FISH_ART[id].legend)));
  save("fish", packRows([frames], T, T), {
    frameWidth: T,
    frameHeight: T,
    frames: Object.fromEntries(FISH_IDS.map((id, i) => [id, i])),
    note: "One icon per fish, in FISH order (shared/content/fish.ts), facing right.",
  });
}

function renderBugs(): void {
  const read = (file: string) => Img.read(path.join(PACK, file));
  save("bugs", packRows(BUG_IDS.map((id) => bugFrames(id, read)), T, T), {
    frameWidth: T,
    frameHeight: T,
    rows: Object.fromEntries(BUG_IDS.map((id, i) => [id, i])),
    layout: `One row per bug in BUGS order (shared/content/bugs.ts): ${BUG_SHEET.flutterFrames} frames of fluttering, then its icon (column ${BUG_SHEET.iconColumn}).`,
  });
}

function renderFishing(): void {
  save("fishing", packRows([fishingFrames((file) => Img.read(path.join(PACK, file)))], T, T), {
    frameWidth: T,
    frameHeight: T,
    frames: FISHING_FRAMES,
    note: "The rod is the pack's own, centred on a 16×16 frame.",
  });
}

console.log(`Rendering sprites into ${path.relative(ROOT, OUT)}${path.sep}`);
renderCrops();
renderSoil();
renderBeachItems();
renderCrate();
renderSeedStand();
renderSand();
renderMarkers();
renderEmotes();
renderUiIcons();
renderSeaside();
renderFish();
renderBugs();
renderFishing();
fs.writeFileSync(path.join(OUT, "manifest.json"), JSON.stringify(manifest, null, 2) + "\n");
console.log("  manifest.json");
