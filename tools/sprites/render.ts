/**
 * Renders our own sprites into client/public/assets/custom/ and writes
 * custom/manifest.json, which names every frame.
 *
 * Run with `npm run sprites` after editing any file in tools/sprites/.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { BEACH_ITEMS, BEACH_LEGEND } from "./beach";
import { crateClosed, crateOpen } from "./crate";
import { CROP_ART, CROP_LEGEND, PACKET, PACKET_PICTURE, SEEDS } from "./crops";
import { Img, fromGrid, outline, packRows } from "./lib/image";
import { SAND_GRASS, SAND_WATER, recolourBlock } from "./sand";
import { soilTile } from "./soil";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const PACK = path.join(ROOT, "client/public/assets/ninja-adventure");
const OUT = path.join(ROOT, "client/public/assets/custom");
const T = 16;

const manifest: Record<string, unknown> = {
  about: "Made for Cozy Farm in Ninja Adventure's style. Generated by `npm run sprites` from tools/sprites/; don't edit the PNGs by hand.",
};

function save(name: string, img: Img, info: Record<string, unknown>): void {
  img.write(path.join(OUT, `${name}.png`));
  manifest[name] = { file: `${name}.png`, width: img.w, height: img.h, ...info };
  console.log(`  ${name}.png  ${img.w}×${img.h}`);
}

function renderCrops(): void {
  const ITEM_COL = 5;
  const PACKET_COL = 6;
  const cols = PACKET_COL + 1;
  const rows: (Img | null)[][] = [];
  const crops: Record<string, unknown> = {};
  Object.entries(CROP_ART).forEach(([id, art], row) => {
    const legend = { ...CROP_LEGEND, ...("seed" in art ? { z: art.seed[0], Z: art.seed[1] } : {}) };
    if (art.stages.includes(SEEDS) && !("seed" in art)) throw new Error(`${id} uses SEEDS but has no seed colours`);
    const frames: (Img | null)[] = Array(cols).fill(null);
    art.stages.forEach((grid, i) => (frames[i] = outline(fromGrid(grid, legend))));
    frames[ITEM_COL] = outline(fromGrid(art.item, legend));
    const packet = fromGrid(PACKET, legend).blit(fromGrid(art.packet, legend), PACKET_PICTURE.x, PACKET_PICTURE.y);
    frames[PACKET_COL] = outline(packet);
    rows.push(frames);
    crops[id] = {
      stages: art.stages.map((_, i) => row * cols + i),
      item: row * cols + ITEM_COL,
      packet: row * cols + PACKET_COL,
    };
  });
  save("crops", packRows(rows, T, T), {
    frameWidth: T,
    frameHeight: T,
    layout: "One row per crop. Columns 0..n-1: growth stages, seed to ripe. Column 5: harvested item. Column 6: seed packet.",
    crops,
  });
}

function renderSoil(): void {
  const dry = Array.from({ length: 16 }, (_, mask) => soilTile(mask, false));
  const wet = Array.from({ length: 16 }, (_, mask) => soilTile(mask, true));
  save("soil", packRows([dry, wet], T, T), {
    frameWidth: T,
    frameHeight: T,
    layout:
      "Row 0 dry, row 1 watered. Frame = mask (+16 if watered), where mask adds 1/2/4/8 for each tilled neighbour to the north/east/south/west.",
  });
}

function renderBeachItems(): void {
  const names = Object.keys(BEACH_ITEMS);
  const frames = names.map((n) => outline(fromGrid(BEACH_ITEMS[n], BEACH_LEGEND)));
  save("beach-items", packRows([frames], T, T), {
    frameWidth: T,
    frameHeight: T,
    frames: Object.fromEntries(names.map((n, i) => [n, i])),
  });
}

function renderCrate(): void {
  save("shipping-crate", packRows([[outline(crateClosed()), outline(crateOpen())]], 32, 32), {
    frameWidth: 32,
    frameHeight: 32,
    frames: { closed: 0, open: 1 },
    note: "Two tiles wide. The box sits on the bottom of the frame.",
  });
}

function renderSand(): void {
  for (const [name, r] of [
    ["sand-grass", SAND_GRASS],
    ["sand-water", SAND_WATER],
  ] as const) {
    const img = recolourBlock(Img.read(path.join(PACK, r.source)), r);
    save(name, img, {
      frameWidth: T,
      frameHeight: T,
      recolouredFrom: `ninja-adventure/${r.source} (block at ${r.x},${r.y}, ${r.w}×${r.h}); same tile layout`,
    });
  }
}

console.log(`Rendering sprites into ${path.relative(ROOT, OUT)}${path.sep}`);
renderCrops();
renderSoil();
renderBeachItems();
renderCrate();
renderSand();
fs.writeFileSync(path.join(OUT, "manifest.json"), JSON.stringify(manifest, null, 2) + "\n");
console.log("  manifest.json");
